"use client";
import { Suspense } from "react";
import { useApiWorkspace } from "@/features/api-workspace/api-workspace-shell";
import { operationAllowed, type OperationArea } from "./permissions";
import { PaymentScreen } from "./payment-screen";
import { WaterScreen } from "./water-screen";
import { PurchaseRequestsScreen } from "./new-module-screens";
import { CustomerPaymentsScreen } from "@/features/customer-payments/payments-screen";
import { SalesInvoiceListScreen } from "@/features/sales-invoice-list/invoice-list-screen";
import { ClaimReportScreen } from "@/features/quality-claims/claim-report-screen";
import { QualityClaimsScreen } from "@/features/quality-claims/quality-claims-screen";
import { SalesReturnsScreen } from "@/features/sales-returns/sales-returns-screen";
import { PayrollScreen } from "@/features/payroll/payroll-screen";
import { PayrollPaymentsScreen } from "@/features/payroll/payroll-payments-screen";
import { SalesPerformanceScreen } from "@/features/sales-reports/sales-performance-screen";
import { PriceTrendScreen } from "@/features/sales-reports/price-trend-screen";
import { AfterSalesIssuesScreen } from "@/features/sales-reports/after-sales-issues-screen";
import { LotTracingScreen } from "@/features/lot-tracing/lot-tracing-screen";
import { PayrollSettingsScreen } from "@/features/payroll-settings/payroll-settings-screen";
import { HarvestYieldScreen } from "@/features/harvest-yield/yield-screen";
import { SalesInvoiceScreen } from "@/features/sales-invoices/invoice-screen";
import { ProductsScreen } from "@/features/sales-api/products-screen";
import { WorkforceScreen } from "./workforce-screen";
import { MyWorkScreen } from "./my-work-screen";
import { CyclesScreen } from "@/features/cultivation-api/screen";
import { CultivationRecordsScreen } from "@/features/cultivation-api/records-screen";
import { JobTypesScreen } from "@/features/labor-api/job-types-screen";
import { PaymentsV2Screen } from "@/features/purchasing-v2/screens";
import { PurchaseReceiptsScreen } from "@/features/purchase-documents/receipts-screen";
export function OperationScreen({ area }: { area: OperationArea }) {
  const context = useApiWorkspace();
  if (!operationAllowed(area, context.identity, context.permissions.functionPermissions)) return <p role="alert">Bạn không có quyền xem chức năng này.</p>;
  if (area === "purchase-receipts") return <Suspense><PurchaseReceiptsScreen /></Suspense>;
  if (process.env.NEXT_PUBLIC_OMTS_PURCHASING_CONTRACT === "v2" && area === "supplier-payments") return <PaymentsV2Screen />;
  if (area === "job-types") return <JobTypesScreen />;
  if (area === "cultivation-cycles") return <CyclesScreen />;
  if (area === "seeding" || area === "material-usages" || area === "harvest") return <CultivationRecordsScreen area={area} />;
  if (area === "sales-products") return <ProductsScreen />;
  if (area === "sales-invoices") return <SalesInvoiceScreen />;
  if (area === "customer-payments") return <CustomerPaymentsScreen />;
  if (area === "harvest-yield") return <HarvestYieldScreen />;
  if (area === "lot-tracing") return <LotTracingScreen />;
  if (area === "sales-invoice-list") return <SalesInvoiceListScreen />;
  if (area === "claim-reports") return <ClaimReportScreen />;
  if (area === "quality-claims") return <QualityClaimsScreen />;
  if (area === "sales-returns") return <SalesReturnsScreen />;
  if (area === "payroll") return <PayrollScreen />;
  if (area === "payroll-payments") return <PayrollPaymentsScreen />;
  if (area === "sales-report") return <SalesPerformanceScreen />;
  if (area === "price-trend-report") return <PriceTrendScreen />;
  if (area === "after-sales-report") return <AfterSalesIssuesScreen />;
  if (area === "payroll-settings") return <PayrollSettingsScreen />;
  if (area === "purchase-requests") return <PurchaseRequestsScreen />;
  if (area === "workforce") return <WorkforceScreen />;
  if (area === "my-work") return <MyWorkScreen />;
  return area === "supplier-payments" ? <PaymentScreen /> : <WaterScreen />;
}
